STANDARD_LIMITATIONS = [
    "Amazon is one sales channel. Revenue also comes from other retailers, direct sales and B2B, so review "
    "tone can only ever explain part of revenue.",
    "Review volume is a biased sample of buyers: unhappy and very happy customers review more often, and "
    "review solicitation programmes shift the mix over time. AbnormalTone differences out a stable bias but "
    "not a changing one.",
    "Fake or incentivised reviews are only partly removed (duplicate text is dropped, as in the paper).",
    "Revenue is the SEC 'as first reported' value; Q4 is derived as fiscal year minus Q1-Q3. No analyst "
    "consensus data is used, so 'growth surprise' is relative to the company's own trend, not to Wall Street.",
    "Jin (2022) is an in-sample study of 292 firms in 1996-2014. A single company over a few years cannot "
    "confirm or reject it; treat hit rates on 8 quarters as anecdotes.",
    "Not investment advice.",
]


def _fmt(v, pct: bool = False) -> str:
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "-"
    if pct:
        return f"{round(v * 100, 1) + 0.0:+.1f}%"  # + 0.0 turns -0.0 into 0.0
    return (f"{v:+.3f}" if isinstance(v, float) else str(v))


def _sources(run: "Run") -> list[str]:
    path = run.dir / "access_log.jsonl"
    if not path.exists():
        return ["No network access was logged."]
    last: dict[str, dict] = {}
    for line in path.read_text().splitlines():
        e = json.loads(line)
        if e.get("kind"):
            continue
        host = urlparse(e.get("url", "")).netloc or e.get("source", "?")
        last[host] = e
    return [f"`{h}`: last attempt {e['ts']}, status {e.get('status')}" + (f" ({e['error'][:120]})"
                                                                         if e.get("error") else "")
            for h, e in sorted(last.items())]


def write_report(run: "Run", quarterly: pd.DataFrame, card: dict, results: dict | None) -> None:
    t = run.company.ticker
    status = run._status()
    reviews = load_reviews(run.dir / "reviews.csv")
    agg = status.get("aggregate", {})
    lines = [f"# {run.company.name} ({t}): Amazon review tone research", "",
             f"As of {run.as_of.isoformat()}. Study `{run.study.name}`, scorer `{run.scorer_name}`. "
             "Generated by `reviewtone`; do not edit by hand.", ""]

    lines += ["## Prediction", ""]
    if "signal_quarter" in card:
        lines += [f"**{card['call_text']}**", "",
                  f"- Signal quarter: {card['signal_quarter']} (ended {card['quarter_end']}), "
                  f"{card['reviews']} product-opinion reviews",
                  f"- Mean tone {_fmt(card['mean_tone'])}; AbnormalTone {_fmt(card['AbnormalTone'])} "
                  f"(call threshold {run.study.rules['negative_swing_threshold']:+.2f})"]
        if card.get("blockers"):
            lines.append(f"- Not callable because: {', '.join(card['blockers'])}")
        if card.get("expected_announcement"):
            lines.append(f"- Revenue for this quarter not yet reported; expected {card['expected_announcement']}")
        if card.get("revenue_already_reported"):
            lines.append(f"- Already reported: growth surprise {_fmt(card.get('outcome_growth_surprise'), True)}")
        if card.get("current_quarter_so_far"):
            c = card["current_quarter_so_far"]
            lines.append(f"- {c['quarter']} so far: {c['reviews']} reviews, AbnormalTone {_fmt(c['AbnormalTone'])} "
                         "(provisional)")
    else:
        lines.append(f"No prediction: {card.get('status', 'insufficient data')}.")
    lines.append("")

    lines += ["## Data", ""]
    if len(reviews):
        lines.append(f"- {len(reviews):,} reviews, {reviews['review_date'].min()} to {reviews['review_date'].max()}, "
                     f"{reviews['asin'].nunique()} ASINs; sources: {', '.join(sorted(reviews['source'].unique()))}")
    else:
        lines.append("- No reviews collected yet.")
    cat = status.get("catalog", {})
    lines.append(f"- products.csv: {cat.get('products', 0)} products ({cat.get('duplicates_removed', 0)} duplicates "
                 "removed)")
    v = status.get("verification", {})
    if v.get("fiscal_year_end_matches") is not None:
        lines.append(f"- SEC: {v.get('sec_name')} (CIK {v.get('cik')}), fiscal year end {v.get('sec_fiscal_year_end')}"
                     f" - {'matches' if v['fiscal_year_end_matches'] else 'DOES NOT MATCH'} config")
    else:
        lines.append(f"- SEC verification not done: {v.get('error', 'not run')}")
    if agg:
        n, target = agg.get("complete_quarters", 0), agg.get("target_complete_quarters", 12)
        flag = "" if agg.get("sufficient") else " - **INSUFFICIENT HISTORY**"
        lines.append(f"- Complete quarters: {n} of {target} sought{flag}; quarters usable for a call: "
                     f"{agg.get('usable_signal_quarters', 0)}")
    lines.append("")

    if len(quarterly):
        lines += ["![tone and counts](charts/tone_and_counts.png)", "", "![negative swing](charts/negative_swing.png)",
                  ""]

    lines += ["## Held-out evaluation", ""]
    if results:
        for key, res in results.items():
            s = res["summary"]
            lines.append(f"**Horizon {key[1:]}** ({'same quarter' if key == 'h0' else 'next quarter'} revenue): "
                         f"{s['calls']} calls in {s['holdout_quarters']} held-out quarters, "
                         f"{s['sales_hits']} hits, {s['sales_misses']} misses; slowdowns that were not called: "
                         f"{s['uncalled_slowdowns']}; base rate of slowdowns {_fmt(s['base_rate_slowdown'], True)}."
                         + (f" _{s['warning']}._" if s.get("warning") else ""))
            lines.append("")
        ev = pd.read_csv(run.dir / "evaluation_h0.csv")
        if len(ev):
            lines += ["| Quarter | Reviews | AbnormalTone | Call | Growth surprise | Announcement CAR | Result |",
                      "|---|---|---|---|---|---|---|"]
            for r in ev.itertuples():
                result = {True: "hit", False: "**MISS**"}.get(r.sales_hit if isinstance(r.sales_hit, bool)
                                                              else None, "")
                if r.call == "no_call" and r.GrowthSurprise < 0:
                    result = "uncalled slowdown"
                lines.append(f"| {r.signal_quarter} | {r.n_reviews} | {_fmt(r.AbnormalTone)} | {r.call} | "
                             f"{_fmt(r.GrowthSurprise, True)} | {_fmt(r.announcement_car, True)} | {result} |")
            lines += ["", "![tone vs sales](charts/tone_vs_sales.png)"]
    else:
        lines.append("Not run: " + status.get("evaluation", {}).get("skipped", "needs tone history and SEC revenue")
                     + ".")
    lines.append("")

    lines += ["## Sources", "", *[f"- {s}" for s in _sources(run)], "",
              "Files: `products.csv`, `reviews.csv` (append-only), `scores.csv` (append-only), `rubric.md`, "
              "`quarterly.csv`, `fundamentals.csv`, `panel.csv`, `evaluation_h*.csv`, `prediction.json`, "
              "`access_log.jsonl`, `history/` (weekly snapshots).", ""]

    lines += ["## Limitations", ""]
    for step, info in status.items():
        if isinstance(info, dict) and info.get("error"):
            lines.append(f"- {step}: {info['error']}")
        if isinstance(info, dict) and info.get("n_errors"):
            lines.append(f"- {step}: {info['n_errors']} fetch errors (see access_log.jsonl)")
    if run.scorer_name == "lexicon":
        lines.append("- Tone came from the offline word-list baseline, which is NOT a research-grade measure.")
    from .catalog import catalog_gaps
    products = pd.read_csv(run.dir / "products.csv", dtype=str) if (run.dir / "products.csv").exists() else \
        pd.DataFrame(columns=["brand", "asin", "parent_asin", "official_store"])
    products["official_store"] = products["official_store"].astype(str).str.lower().eq("true")
    lines += [f"- {g}" for g in catalog_gaps(products, reviews, run.company)]
    lines += [f"- {s}" for s in STANDARD_LIMITATIONS]
    (run.dir / "README.md").write_text("\n".join(lines) + "\n")
